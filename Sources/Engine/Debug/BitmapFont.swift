/// A tiny 5x7 pixel font covering digits, uppercase letters and common punctuation.
/// Lowercase input is drawn uppercase; unknown characters render as '?'.
enum BitmapFont {
    static let glyphWidth = 5
    static let glyphHeight = 7
    /// Horizontal advance per character, including one column of spacing.
    static let advance = 6

    /// For each row (top to bottom), the horizontal runs of lit pixels as (start column, length).
    static func runs(for character: Character) -> [[(start: Int, length: Int)]] {
        let key = Character(character.uppercased())
        return glyphs[key] ?? glyphs["?"]!
    }

    private static let glyphs: [Character: [[(start: Int, length: Int)]]] = source.mapValues { pattern in
        pattern.split(separator: "|").map { row in
            var runs: [(Int, Int)] = []
            var start: Int?
            for (column, pixel) in row.enumerated() {
                if pixel == "#" {
                    if start == nil { start = column }
                } else if let s = start {
                    runs.append((s, column - s))
                    start = nil
                }
            }
            if let s = start { runs.append((s, row.count - s)) }
            return runs
        }
    }

